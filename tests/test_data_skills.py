def test_windows():
    asof, first = pd.Timestamp("2026-10-13"), pd.Timestamp("2024-01-01")
    w = _time.window("month_to_date", asof, first)
    assert (str(w.start.date()), str(w.prev_start.date()), str(w.prev_end.date())) == ("2026-10-01", "2026-09-01", "2026-09-13")
    w = _time.window("year_to_date", asof, first)
    assert (str(w.start.date()), str(w.prev_end.date())) == ("2026-01-01", "2025-10-13")
    w = _time.window("last_4_weeks", asof, first)
    assert (w.end - w.start).days == 27 and (w.prev_end - w.prev_start).days == 27
    # Month-end edge: Oct 31 compares with Sep 1–30, not into October.
    w = _time.window("month_to_date", pd.Timestamp("2026-10-31"), first)
    assert str(w.prev_end.date()) == "2026-09-30"


def test_week_over_week_and_partial_periods():
    df = pd.DataFrame({"d": pd.date_range("2026-01-05", "2026-01-21"), "v": 1.0})   # Mon Jan 5 .. Wed Jan 21
    s = _time.period_series(df, "d", "v", "wow")
    assert s["value"].tolist() == [7.0, 7.0, 3.0]
    assert s["partial"].tolist() == [False, False, True]
    assert s.loc[1, "pct_change"] == 0.0
    m = _time.period_series(df.assign(d=pd.date_range("2026-01-10", periods=17)), "d", "v", "mom")
    assert m["partial"].iloc[0]        # data starts Jan 10 -> January is partial


